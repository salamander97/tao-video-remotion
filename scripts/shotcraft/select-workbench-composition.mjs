#!/usr/bin/env node
// Safe, explicit selector for which composition's manifest the TOP-LEVEL
// `template/src/workbench.ts` re-exports.
//
// WHY THIS FILE EXISTS: Shotcraft's own Workbench (`workbench/scripts/
// open.mjs` + `gen-index.mjs`) links a project's `src/` directory as
// `workbench/proj` and only ever checks for a manifest AT THE TOP of that
// linked directory (`proj/workbench.ts` — see `gen-index.mjs`'s
// `hasManifest` check and `projectCards.ts`'s static `import { WORKBENCH }
// from "@proj/workbench"`). This repo has MULTIPLE compositions, each with
// its own manifest nested one level down (`template/src/AiflPromoDemo/
// workbench.ts`, `template/src/DiBo10PhutSauAn/workbench.ts`) — a nested-only
// manifest is INVISIBLE to the real import/parity pipeline, which is exactly
// the gap this script (and `template/src/workbench.ts`) closes. Both nested
// manifests are preserved untouched; this only rewrites the small top-level
// re-export file.
//
// Usage:
//   node scripts/shotcraft/select-workbench-composition.mjs AiflPromoDemo
//   node scripts/shotcraft/select-workbench-composition.mjs DiBo10PhutSauAn
import { writeFile, readdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const TEMPLATE_SRC = path.join(REPO_ROOT, "template/src");
const OUT_FILE = path.join(TEMPLATE_SRC, "workbench.ts");

async function listAvailableCompositions() {
  const out = [];
  for (const entry of await readdir(TEMPLATE_SRC, { withFileTypes: true })) {
    if (entry.isDirectory() && existsSync(path.join(TEMPLATE_SRC, entry.name, "workbench.ts"))) out.push(entry.name);
  }
  return out.sort();
}

async function main() {
  const target = process.argv[2];
  const available = await listAvailableCompositions();
  if (!target || !available.includes(target)) {
    console.error(`Usage: select-workbench-composition.mjs <composition>\nAvailable (have a nested workbench.ts): ${available.join(", ")}`);
    process.exitCode = 1;
    return;
  }
  const content =
    `// AUTO-GENERATED by scripts/shotcraft/select-workbench-composition.mjs — DO NOT hand-edit the export path.\n` +
    `// Top-level manifest re-export so Shotcraft's Workbench (which only checks\n` +
    `// \`<linked-src>/workbench.ts\`, never nested paths — see the header comment\n` +
    `// in the generator script) can see one of this repo's multiple compositions.\n` +
    `// Currently selected: ${target}. Switch with:\n` +
    `//   node scripts/shotcraft/select-workbench-composition.mjs <${available.join("|")}>\n` +
    `// Both nested manifests remain fully intact regardless of this selection —\n` +
    `// see template/src/${target === "AiflPromoDemo" ? "DiBo10PhutSauAn" : "AiflPromoDemo"}/workbench.ts.\n` +
    `export { WORKBENCH } from "./${target}/workbench";\n`;
  await writeFile(OUT_FILE, content);
  console.log(`Selected "${target}" — wrote ${OUT_FILE}`);
}

main().catch((error) => { console.error(error.stack); process.exitCode = 1; });
