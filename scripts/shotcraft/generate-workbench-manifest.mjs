#!/usr/bin/env node
// Reusable generator: produces a `src/workbench.ts` manifest (matching
// `workbench/src/cards/manifest.ts`'s `WorkbenchManifest` type — see
// `vendor/shotcraft/workbench.md` §2) for the vertical, TTS-first
// composition pattern this repo actually uses (`<Series><Series.Sequence
// durationInFrames={audioManifest.scenes[i].durationInFrames + buffer}>`),
// NOT just the horizontal Shotcraft-native `SHOTS`/`SFX` table pattern
// AiflPromoDemo already covers by hand (workbench.ts is same-origin there).
//
// Usage:
//   node scripts/shotcraft/generate-workbench-manifest.mjs <compositionDir> \
//     --name "Composition Name" --width 1080 --height 1920 \
//     --scenes Scene1Hook:3,Scene2Eat:3,...,Scene8Outro:10
//
// `--scenes` is `<ComponentName>:<bufferFrames>` pairs, in Series order,
// matching this repo's `+3/scene, +10 last scene` snappy-transition
// convention (see SKILL.md §3.4) — durations themselves come from the
// composition's own `audioData.ts` (`audioManifest.scenes[i].durationInFrames`),
// never re-typed by hand, so the manifest can't drift from what renders.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

function parseArgs(argv) {
  const opts = { scenes: [] };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--name") opts.name = argv[++i];
    else if (argv[i] === "--width") opts.width = Number(argv[++i]);
    else if (argv[i] === "--height") opts.height = Number(argv[++i]);
    else if (argv[i] === "--fps") opts.fps = Number(argv[++i]);
    else if (argv[i] === "--scenes") opts.scenes = argv[++i].split(",").map((pair) => {
      const [component, buffer] = pair.split(":");
      return { component, buffer: Number(buffer) };
    });
  }
  return opts;
}

async function main() {
  const [compositionDir, ...rest] = process.argv.slice(2);
  if (!compositionDir) throw new Error("Usage: generate-workbench-manifest.mjs <compositionDir> --name X --width W --height H --scenes A:3,B:3,...");
  const opts = parseArgs(rest);
  if (!opts.name || !opts.width || !opts.height || !opts.scenes.length) throw new Error("--name, --width, --height, --scenes are all required");
  const fps = opts.fps ?? 30;

  const audioManifest = JSON.parse(await readFile(path.join(compositionDir, "audio-manifest.json"), "utf8").catch(async () => {
    // fall back to reading audioData.ts's exported JSON-shaped literal is
    // out of scope for a static generator without a TS parser — projects
    // using this generator should also emit audio-manifest.json alongside
    // audioData.ts (a cheap addition: `JSON.stringify(audioManifest)`).
    throw new Error(`Missing ${path.join(compositionDir, "audio-manifest.json")} — export audioManifest to JSON alongside audioData.ts for this generator to read real durations, not guess them.`);
  }));

  let visualPlan = null;
  try {
    visualPlan = JSON.parse(await readFile(path.join(compositionDir, "visual-plan.json"), "utf8"));
  } catch { /* optional — narration/label enrichment only */ }
  const planScenes = visualPlan ? (Array.isArray(visualPlan) ? visualPlan : visualPlan.scenes) : null;

  let acc = 0;
  const shots = opts.scenes.map((s, i) => {
    const duration = audioManifest.scenes[i].durationInFrames + s.buffer;
    const from = acc;
    acc += duration;
    const narration = planScenes?.[i]?.narration;
    return { id: audioManifest.scenes[i].id ?? s.component, component: s.component, from, duration, narration };
  });
  const total = acc;

  const importLines = shots.map((s) => `import { ${s.component} } from './scenes/${s.component}';`);
  const shotEntries = shots.map((s) =>
    `  { id: ${JSON.stringify(s.id)}, label: ${JSON.stringify(s.narration ? s.narration.slice(0, 40) : s.component)}, from: ${s.from}, duration: ${s.duration}, component: ${s.component} as React.ComponentType<Record<string, unknown>> },`,
  );

  const content = `// AUTO-GENERATED by scripts/shotcraft/generate-workbench-manifest.mjs — same-origin
// with audioManifest (this file re-derives \`from\`/\`duration\` the exact same
// way the composition itself does; do not hand-edit durations here, re-run
// the generator instead if scene buffers change).
${importLines.join("\n")}
import type { WorkbenchManifest } from '../../../workbench/src/cards/manifest';

export const WORKBENCH: WorkbenchManifest = {
  name: ${JSON.stringify(opts.name)},
  fps: ${fps},
  width: ${opts.width},
  height: ${opts.height},
  total: ${total},
  shots: [
${shotEntries.join("\n")}
  ],
};
`;
  const outPath = path.join(compositionDir, "workbench.ts");
  await writeFile(outPath, content);
  console.log(`Wrote ${outPath} (${shots.length} shots, ${total} total frames)`);
}

main().catch((error) => { console.error(error.stack); process.exitCode = 1; });
